"""Build the source ledger: every source behind a published record, when it was last read, and when it is due again.

    python3 scripts/mining/ledger.py           # rewrite data/mining/source-ledger.json
    python3 scripts/mining/ledger.py --check   # fail if the committed ledger is out of date
    python3 scripts/mining/ledger.py --due     # also print the sources that are due today

The ledger is the recheck queue. It reads only files in this repository, so the result is the same on any machine.
"""
import argparse
import json
import sys
from collections import defaultdict
from datetime import date

import common as c


def build():
    rows = defaultdict(lambda: {'states': set(), 'kinds': set(), 'records': 0, 'reviewed': []})
    for state in c.registry():
        offices, records = c.state_records(state)
        for office in offices:
            for url in c.office_sources(office):
                row = rows[url]
                row['states'].add(state['code'])
                row['kinds'].add('veterans_office')
                row['records'] += 1
                if office.get('reviewed_on'):
                    row['reviewed'].append(office['reviewed_on'])
        for record in records:
            kind = record.get('regional_role') if record.get('regional_role') in c.CADENCE_DAYS else 'program'
            for url in c.record_sources(record):
                row = rows[url]
                row['states'].add(record.get('state') or state['code'])
                row['kinds'].add(kind)
                row['records'] += 1
                if c.record_reviewed_on(record):
                    row['reviewed'].append(c.record_reviewed_on(record))
    out = []
    for url in sorted(rows, key=c.url_key):
        row = rows[url]
        reviewed = sorted(row['reviewed'])
        cadence = min(c.CADENCE_DAYS[k] for k in row['kinds'])
        oldest = reviewed[0] if reviewed else None
        out.append({
            'url': url,
            'states': sorted(row['states']),
            'kinds': sorted(row['kinds']),
            'records': row['records'],
            'oldest_review': oldest,
            'newest_review': reviewed[-1] if reviewed else None,
            'cadence_days': cadence,
            'due_on': c.add_days(oldest, cadence) if oldest else None,
        })
    return {
        'about': 'Every source URL behind a published veterans office, program or referral record, with the oldest '
                 'and newest review of the records that rest on it and the date it is next due (oldest review plus '
                 'the cadence for its kind: 90 days for offices and aging agencies, 180 for programs). Generated by '
                 'scripts/mining/ledger.py; do not edit by hand.',
        'sources': out,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--due', action='store_true')
    ap.add_argument('--today', default=date.today().isoformat())
    args = ap.parse_args()
    ledger = build()
    text = json.dumps(ledger, ensure_ascii=False, indent=1) + '\n'
    ok = c.check_or_write(c.MINING / 'source-ledger.json', text, args.check)
    due = [s for s in ledger['sources'] if s['due_on'] and s['due_on'] <= args.today]
    print(f"{len(ledger['sources'])} sources behind {sum(s['records'] for s in ledger['sources'])} record links; "
          f"{len(due)} due by {args.today}.")
    if args.due:
        for s in sorted(due, key=lambda s: (s['due_on'], -s['records'])):
            print(f"  {s['due_on']}  {','.join(s['states'])[:20]:20}  {s['records']:4}  {s['url']}")
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
